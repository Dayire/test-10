import { defineConfig } from 'vite';
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';

// The hosted build: hashed file names (cache-first forever), base './' (any sub-path), and a service worker
// generated from what the build wrote: cache-first for this version's assets, network-first for the page, so
// the game reloads offline once it has been played online (FULL_GAME §8.7).
function serviceWorker() {
  let out = '';
  const walk = (d, base = '') => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name), `${base}${e.name}/`) : [`${base}${e.name}`]));
  return {
    name: 'medina-sw',
    apply: 'build',
    configResolved(c) { out = path.resolve(c.root, c.build.outDir); },
    closeBundle() {
      if (!fs.existsSync(out)) return;
      const files = walk(out).filter((f) => f !== 'sw.js' && !f.endsWith('.map') && !/\.(glb|gltf|bin)$/.test(f));
      const hash = crypto.createHash('sha1');
      for (const f of files.sort()) hash.update(f).update(fs.readFileSync(path.join(out, f)));
      const version = `medina-${hash.digest('hex').slice(0, 12)}`;
      const pre = ['./', ...files.map((f) => `./${f}`)];
      fs.writeFileSync(path.join(out, 'sw.js'), SW.replace('__VERSION__', version).replace('__PRECACHE__', JSON.stringify(pre)));
    },
  };
}
const SW = `// generated by vite.config.js: network-first for the page, cache-first for the assets of this version
const VERSION = '__VERSION__';
const PRECACHE = __PRECACHE__;
const HASHED = /\\/assets\\/(?!models\\/)[^/]+-[A-Za-z0-9_-]{8}\\.[a-z0-9]+$/; // the build's [name]-[hash] files
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(PRECACHE.map((u) => new Request(new URL(u, self.registration.scope), { cache: 'reload' })))).then(() => self.skipWaiting()));
});
// a tab opened before this version may still import the previous build's hashed chapter chunks: the previous
// version's cache stays, older ones go
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => {
    const old = ks.filter((k) => k.startsWith('medina-') && k !== VERSION);
    return Promise.all(old.slice(0, -1).map((k) => caches.delete(k)));
  }).then(() => self.clients.claim()));
});
// this version's cache answers first; the previous one only for hashed names (an unhashed file, such as the
// manifest, an icon or a model override, is never served stale from it) or when the network is gone
const any = (r) => caches.match(r, { ignoreSearch: true });
async function asset(r, u) {
  const c = await caches.open(VERSION);
  const hit = (await c.match(r, { ignoreSearch: true })) || (HASHED.test(u.pathname) ? await any(r) : null);
  if (hit) return hit;
  try {
    const res = await fetch(r);
    if (res.ok && /\\/assets\\//.test(u.pathname)) c.put(r, res.clone());
    return res;
  } catch (err) { const old = await any(r); if (old) return old; throw err; }
}
async function page(r) {
  const c = await caches.open(VERSION);
  try {
    const res = await fetch(r);
    if (res.ok) c.put(r, res.clone());
    return res;
  } catch (err) {
    const hit = (await c.match(r, { ignoreSearch: true })) || (await c.match(new URL('./', self.registration.scope))) || (await any(r));
    if (hit) return hit;
    throw err;
  }
}
self.addEventListener('fetch', (e) => {
  const r = e.request;
  if (r.method !== 'GET') return;
  const u = new URL(r.url);
  if (u.origin !== self.location.origin) return;
  const nav = r.mode === 'navigate' || u.pathname.endsWith('/') || u.pathname.endsWith('.html');
  e.respondWith(nav ? page(r) : asset(r, u));
});
`;

export default defineConfig({
  base: './',
  plugins: [serviceWorker()],
  build: {
    target: 'es2022',
    outDir: 'dist',
    assetsInlineLimit: 0,
    chunkSizeWarningLimit: 2000,
    rollupOptions: {
      output: {
        entryFileNames: 'assets/[name]-[hash].js',
        chunkFileNames: 'assets/[name]-[hash].js',
        assetFileNames: 'assets/[name]-[hash][extname]',
      },
    },
  },
  server: { host: '127.0.0.1', watch: { ignored: ['**/shots/**', '**/tools/**', '**/docs/**', '**/dist/**', '**/dist-artifact/**'] } },
});
